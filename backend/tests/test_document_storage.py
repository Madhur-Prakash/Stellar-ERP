@pytest.mark.integration
class TestUploadDownloadIntegrity:
    """The requirement in one place: the file downloaded is the file uploaded.

    Uses the real endpoints, so this covers the router, the service, the compression, the
    ``BYTEA`` column, the decompression, and the digest verification in one pass. Reuses the
    fixtures from ``test_ocr_api`` rather than rebuilding an organization with document
    permissions, because that setup is substantial and duplicating it would let the two drift.
    """

    async def test_downloaded_bytes_are_identical_to_the_upload(
        self, authed_client: AsyncClient, api: str
    ) -> None:
        from tests.test_ocr_api import invoice_pdf, upload

        original = invoice_pdf()
        document = (await upload(authed_client, api, original))["document"]

        response = await authed_client.get(f"{api}/documents/{document['id']}/file")

        assert response.status_code == 200
        assert response.content == original
        assert sha256_of(response.content) == document["sha256"]

    async def test_a_large_document_round_trips(self, authed_client: AsyncClient, api: str) -> None:
        """Multi-megabyte, so the payload is well past any single-chunk path."""
        from tests.test_ocr_api import upload

        original = text_pdf(lines=20_000)
        assert len(original) > 1_000_000

        document = (await upload(authed_client, api, original))["document"]
        response = await authed_client.get(f"{api}/documents/{document['id']}/file")

        assert response.status_code == 200
        assert response.content == original

    async def test_the_stored_row_is_smaller_than_the_upload(
        self, db: AsyncSession, authed_client: AsyncClient, api: str
    ) -> None:
        """Compression is actually happening on the request path, not only in unit tests."""
        from tests.test_ocr_api import upload

        original = text_pdf(lines=2_000)
        document = (await upload(authed_client, api, original))["document"]

        blob = (
            await db.execute(select(DocumentBlob).where(DocumentBlob.sha256 == document["sha256"]))
        ).scalar_one()

        assert blob.compression is Codec.ZLIB
        assert blob.compressed_size < len(original)
        assert blob.original_size == len(original)

    async def test_an_image_upload_round_trips(self, authed_client: AsyncClient, api: str) -> None:
        """A PNG is already compressed, so this is the Codec.NONE path over HTTP."""
        from tests.test_ocr_api import upload

        try:
            from PIL import Image
        except ImportError:  # pragma: no cover - Pillow arrives via qrcode[pil]
            pytest.skip("Pillow is not installed")

        buffer = io.BytesIO()
        Image.new("RGB", (400, 300), (240, 240, 240)).save(buffer, format="PNG")
        original = buffer.getvalue()

        document = (await upload(authed_client, api, original, filename="scan.png"))["document"]
        response = await authed_client.get(f"{api}/documents/{document['id']}/file")

        assert response.status_code == 200
        assert response.content == original

    async def test_the_blob_is_gone_after_a_rolled_back_upload(
        self, db: AsyncSession, organization: Organization
    ) -> None:
        """The reason blobs belong in the database rather than beside it.

        A write to a filesystem or a bucket is not in the transaction, so a request that
        failed after storing bytes leaked them permanently - orphans nobody would ever look
        for. Here the blob is in the same transaction as everything else, so it goes when the
        transaction goes. Demonstrated with a savepoint, which is what the request-scoped
        session actually uses.
        """
        payload = text_pdf()
        key = key_for(organization, payload)
        store = DatabaseDocumentStore(db, organization.id)

        savepoint = await db.begin_nested()
        await store.write(key, payload, Meta())
        assert await store.exists(key)
        await savepoint.rollback()

        assert not await store.exists(key)
