@pytest.mark.integration
class TestDatabaseDocumentStore:
    async def test_write_then_read_is_byte_identical(
        self, store: DatabaseDocumentStore, organization: Organization
    ) -> None:
        payload = text_pdf()
        key = key_for(organization, payload)

        await store.write(key, payload, Meta())
        assert await store.read(key) == payload

    async def test_read_verifies_against_the_digest(
        self, store: DatabaseDocumentStore, organization: Organization
    ) -> None:
        payload = text_pdf()
        key = key_for(organization, payload)
        await store.write(key, payload, Meta())

        assert await store.read(key, verify=sha256_of(payload)) == payload

        with pytest.raises(BlobCorruptedError):
            await store.read(key, verify="0" * 64)

    async def test_bytes_are_stored_compressed(
        self, db: AsyncSession, store: DatabaseDocumentStore, organization: Organization
    ) -> None:
        """The database must hold the compressed form, not the original.

        Asserted on the column rather than through the store, because reading through the
        store decompresses - which is exactly what would hide a backend that quietly stored
        the raw upload.
        """
        payload = text_pdf()
        key = key_for(organization, payload)
        await store.write(key, payload, Meta())

        blob = (
            await db.execute(select(DocumentBlob).where(DocumentBlob.storage_key == key))
        ).scalar_one()

        assert blob.compression is Codec.ZLIB
        assert blob.data != payload
        assert blob.compressed_size < blob.original_size
        assert blob.original_size == len(payload)
        assert blob.compressed_size == len(blob.data)
        assert zlib.decompress(blob.data) == payload

    async def test_metadata_is_recorded(
        self, db: AsyncSession, store: DatabaseDocumentStore, organization: Organization
    ) -> None:
        payload = text_pdf()
        key = key_for(organization, payload)
        await store.write(key, payload, Meta(filename="supplier bill.pdf"))

        blob = (
            await db.execute(select(DocumentBlob).where(DocumentBlob.storage_key == key))
        ).scalar_one()

        assert blob.original_filename == "supplier bill.pdf"
        assert blob.mime_type == "application/pdf"
        assert blob.sha256 == sha256_of(payload)
        assert blob.organization_id == organization.id
        assert blob.uploaded_at is not None

    async def test_writing_the_same_key_twice_stores_one_row(
        self, db: AsyncSession, store: DatabaseDocumentStore, organization: Organization
    ) -> None:
        """Content-addressed, so a second write of the same bytes is a no-op."""
        payload = text_pdf()
        key = key_for(organization, payload)

        await store.write(key, payload, Meta())
        await store.write(key, payload, Meta())

        count = (
            await db.execute(
                select(func.count())
                .select_from(DocumentBlob)
                .where(DocumentBlob.storage_key == key)
            )
        ).scalar_one()
        assert count == 1

    async def test_missing_blob_is_410_not_404(self, store: DatabaseDocumentStore) -> None:
        """The reference is valid and the content is gone - a different thing from a typo."""
        with pytest.raises(BlobMissingError) as caught:
            await store.read("nonexistent/aa/deadbeef.pdf")
        assert caught.value.status_code == 410

    async def test_exists(self, store: DatabaseDocumentStore, organization: Organization) -> None:
        payload = text_pdf()
        key = key_for(organization, payload)

        assert not await store.exists(key)
        await store.write(key, payload, Meta())
        assert await store.exists(key)

    async def test_delete_removes_the_row(
        self, db: AsyncSession, store: DatabaseDocumentStore, organization: Organization
    ) -> None:
        payload = text_pdf()
        key = key_for(organization, payload)
        await store.write(key, payload, Meta())

        await store.delete(key)

        assert not await store.exists(key)
        with pytest.raises(BlobMissingError):
            await store.read(key)

    async def test_deleting_something_absent_is_not_an_error(
        self, store: DatabaseDocumentStore
    ) -> None:
        await store.delete("nothing/aa/here.pdf")

    async def test_incompressible_input_round_trips_through_the_store(
        self, db: AsyncSession, store: DatabaseDocumentStore, organization: Organization
    ) -> None:
        """The Codec.NONE path has to work end to end, not just in the codec."""
        payload = incompressible()
        key = relative_path_for(organization.id, sha256_of(payload), DocumentFormat.JPEG)

        await store.write(key, payload, Meta(filename="scan.jpg", mime="image/jpeg"))

        blob = (
            await db.execute(select(DocumentBlob).where(DocumentBlob.storage_key == key))
        ).scalar_one()
        assert blob.compression is Codec.NONE
        assert blob.compressed_size == blob.original_size
        assert await store.read(key, verify=sha256_of(payload)) == payload

    async def test_a_tenant_cannot_read_another_tenants_blob(
        self, db: AsyncSession, organization: Organization
    ) -> None:
        """Isolation is a SQL predicate, not a convention about key prefixes.

        The key embeds the organization id, so a store that filtered only by key would appear
        to work. This asserts the `WHERE organization_id = ...` is really there, by asking a
        store scoped to a different tenant for a key it can name exactly.
        """
        payload = text_pdf()
        key = key_for(organization, payload)
        await DatabaseDocumentStore(db, organization.id).write(key, payload, Meta())

        intruder = DatabaseDocumentStore(db, uuid.uuid4())
        assert not await intruder.exists(key)
        with pytest.raises(BlobMissingError):
            await intruder.read(key)


