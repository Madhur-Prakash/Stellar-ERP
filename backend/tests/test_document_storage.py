class TestCompressionRoundTrip:
    """The property everything else depends on."""

    # `pytest.param(..., id=...)` rather than a bare list, and the id is load-bearing on
    # Windows: pytest derives the node id from the parameter's repr and exports it as
    # PYTEST_CURRENT_TEST, where a 200 KB payload trips the 32767-character limit on an
    # environment variable and every case in this class errors out before it runs.
    @pytest.mark.parametrize(
        "payload",
        [
            pytest.param(b"", id="empty"),
            pytest.param(b"\x00", id="one-byte"),
            pytest.param(b"%PDF-1.7\n", id="tiny"),
            pytest.param(b"A" * 100_000, id="highly-compressible"),
            pytest.param(text_pdf(), id="text-pdf"),
            pytest.param(incompressible(), id="incompressible"),
            pytest.param(bytes(range(256)) * 500, id="all-byte-values"),
            pytest.param(b"\x00" * 50_000, id="null-bytes"),
        ],
    )
    def test_byte_identical(self, payload: bytes) -> None:
        result = compress_sync(payload)
        assert decompress_sync(result.codec, result.payload) == payload

    def test_digest_survives_the_round_trip(self) -> None:
        """The check that actually runs on every download.

        `document.sha256` covers the *original* bytes, so a codec that rewrote anything would
        make every download raise `BlobCorruptedError`.
        """
        original = text_pdf()
        digest = sha256_of(original)

        result = compress_sync(original)
        assert sha256_of(decompress_sync(result.codec, result.payload)) == digest

    async def test_async_wrappers_agree_with_the_sync_ones(self) -> None:
        payload = text_pdf()
        result = await compress(payload)
        assert await decompress(result.codec, result.payload) == payload


class TestCompressionDecisions:
    """When compressing is worth it, and when storing verbatim is the right answer."""

    def test_a_text_pdf_compresses_substantially(self) -> None:
        result = compress_sync(text_pdf())
        assert result.codec is Codec.ZLIB
        # The fixture is repetitive invoice lines, so this is the good case. Asserted as a
        # floor rather than a range: a future codec change may beat it and must not fail here.
        assert result.saving_ratio > 0.5, f"only saved {result.saving_ratio:.1%}"

    def test_incompressible_input_is_stored_verbatim(self) -> None:
        """A scan or a JPEG has nothing left to give, and that is not a failure.

        Storing a 0.1%-smaller payload would cost a full decompression pass on every download
        of it, forever - so the codec has to be allowed to decline.
        """
        payload = incompressible()
        result = compress_sync(payload)
        assert result.codec is Codec.NONE
        assert result.payload is payload
        assert result.stored_size == len(payload)

    def test_marginal_gains_are_declined(self) -> None:
        """A saving under the floor is not worth the read-side price.

        Constructed rather than found: mostly-random bytes with a small compressible tail, so
        zlib finds *something* but not enough. Asserting the premise first means a future
        codec change makes this test say "the fixture is no longer marginal" instead of
        silently testing nothing.
        """
        payload = incompressible(100_000) + b"A" * 2_000
        gained = 1 - len(zlib.compress(payload, level=6)) / len(payload)
        assert 0 < gained < MIN_SAVING_RATIO, f"fixture gained {gained:.2%} - adjust it"
        assert compress_sync(payload).codec is Codec.NONE

    def test_tiny_input_is_not_even_attempted(self) -> None:
        payload = b"%PDF-1.4 tiny"
        assert len(payload) < MIN_WORTH_TRYING
        assert compress_sync(payload).codec is Codec.NONE

    def test_sizes_and_ratio_are_reported(self) -> None:
        payload = text_pdf()
        result = compress_sync(payload)
        assert result.original_size == len(payload)
        assert result.stored_size == len(result.payload)
        assert result.saving_ratio == pytest.approx(1 - result.stored_size / result.original_size)

    def test_empty_input_has_a_defined_ratio(self) -> None:
        """Guards a division by zero on a degenerate but reachable input."""
        assert compress_sync(b"").saving_ratio == 0.0


class TestDecompressionFailures:
    def test_corrupt_payload_raises(self) -> None:
        result = compress_sync(text_pdf())
        assert result.codec is Codec.ZLIB
        with pytest.raises(DecompressionError):
            decompress_sync(Codec.ZLIB, result.payload[:-40] + b"garbage")

    def test_unknown_codec_is_a_clear_error(self) -> None:
        """A blob written by a newer version must say so, not raise a bare ValueError."""
        with pytest.raises(DecompressionError, match="Unknown compression codec"):
            decompress_sync("brotli-9", b"whatever")

    def test_codec_accepted_as_a_plain_string(self) -> None:
        """It arrives from a database column, which yields a str under some drivers."""
        result = compress_sync(text_pdf())
        assert decompress_sync(str(result.codec), result.payload) == text_pdf()


