def text_pdf(lines: int = 400) -> bytes:
    """A digital PDF with a text layer - the best case for compression.

    Deliberately repetitive: this stands in for an invoice generated by accounting software,
    which is what most uploads to this system actually are.
    """
    buffer = io.BytesIO()
    _write_simple_pdf(
        buffer,
        "\n".join(
            f"INVOICE LINE {index:04d}  QTY 10  RATE 1500.00  AMOUNT 15000.00"
            for index in range(lines)
        ),
    )
    return buffer.getvalue()


def incompressible(size: int = 200_000) -> bytes:
    """Bytes with no structure left to exploit.

    Stands in for a scanned PDF or a JPEG, whose image streams are already entropy-coded.

    Seeded rather than ``os.urandom`` so a failure is reproducible, and genuinely random
    rather than an arithmetic pattern: the first version of this generated bytes from
    ``(index * 7919 + ...) % 251``, which *looks* like noise and which zlib compressed by 30%
    - so the test asserting "incompressible input is stored verbatim" failed against a
    perfectly correct codec. A pattern a human cannot see is not a pattern zlib cannot see.
    """
    # S311 (not a CSPRNG) is the point, not an oversight: this needs bytes that are
    # reproducible across runs, which `secrets` deliberately cannot provide. Nothing here is
    # a credential - it is filler chosen to have no structure for zlib to find.
    return random.Random(20260805).randbytes(size)  # noqa: S311


class Meta:
    """Minimal ``BlobMetadata``."""

    def __init__(self, filename: str = "invoice.pdf", mime: str = "application/pdf") -> None:
        self.original_filename = filename
        self.mime_type = mime
        self.uploaded_by_user_id = None


@pytest.fixture
def store(db: AsyncSession, organization: Organization) -> DatabaseDocumentStore:
    return DatabaseDocumentStore(db, organization.id)


def key_for(organization: Organization, data: bytes) -> str:
    return relative_path_for(organization.id, sha256_of(data), DocumentFormat.PDF)


