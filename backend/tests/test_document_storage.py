"""Document blobs in PostgreSQL: compression, storage, and the round trip.

The claim under test is narrow and absolute: **what comes out is byte-identical to what went
in.** Everything else here supports that. A document is the evidence behind a posted ledger
entry, and ``document.sha256`` - the digest of the original upload - is simultaneously the
duplicate key, the storage address, and the integrity check applied on download. A round trip
that returned an equivalent-but-different file would fail all three at once, so "close enough"
is not a category that exists in this module.

The compression tests are pure and need nothing running. The store and HTTP tests need
PostgreSQL and are marked ``integration``.
"""

